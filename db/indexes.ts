import type { Db } from 'mongodb';

export async function ensureIndexes(db: Db) {
  await Promise.all([
    db.collection('monitor_events').createIndex({id:1},{unique:true}),
    db.collection('monitor_events').createIndex({created:1,name:1}),
    db.collection('monitor_api').createIndex({hour:1,key:1},{unique:true}),
    db.collection('monitor_api').createIndex({created:1}),
    db.collection('monitor_budget').createIndex({key:1},{unique:true}),
    db.collection('monitor_ack').createIndex({key:1},{unique:true}),
    db.collection('monitor_tasks').createIndex({key:1},{unique:true}),
    db.collection('monitor_checks').createIndex({created:-1}),
    ...['monitor_events','monitor_api','monitor_checks','monitor_budget','monitor_audit'].map(name=>db.collection(name).createIndex({expires:1},{expireAfterSeconds:0})),
    ...['accounts', 'posts', 'photos', 'comments', 'trips', 'reports', 'destinations', 'places', 'moderation_actions'].map(name => db.collection(name).createIndex({ id: 1 }, { unique: true })),
    db.collection('accounts').createIndex({ username: 1 }, { unique: true, partialFilterExpression: { username: { $type: 'string' } } }),
    db.collection('trips').createIndex({ user_id: 1, key: 1 }, { unique: true }),
    db.collection('trip_items').createIndex({ trip_id: 1, kind: 1, target_id: 1 }, { unique: true }),
    db.collection('trip_items').createIndex({ user_id: 1 }),
    db.collection('reports').createIndex({ user_id: 1, kind: 1, target_id: 1 }, { unique: true }),
    db.collection('reports').createIndex({ status: 1, created: 1 }),
    db.collection('posts').createIndex({ destination_id: 1, created: -1 }),
    db.collection('comments').createIndex({ post_id: 1, created: 1 }),
    db.collection('accounts').createIndex({ google_sub: 1 }, { unique: true }),
    db.collection('sessions').createIndex({ token_hash: 1 }, { unique: true }),
    db.collection('sessions').createIndex({ expires: 1 }, { expireAfterSeconds: 0 }),
    db.collection('login_nonces').createIndex({ token_hash: 1 }, { unique: true }),
    db.collection('login_nonces').createIndex({ expires: 1 }, { expireAfterSeconds: 0 }),
    db.collection('posts').createIndex({ created: -1 }),
    db.collection('posts').createIndex({ photos: 1 }),
    db.collection('comments').createIndex({ created: -1 }),
    db.collection('votes').createIndex({ post_id: 1, user_id: 1, kind: 1 }, { unique: true }),
    db.collection('saves').createIndex({ post_id: 1, user_id: 1 }, { unique: true }),
    db.collection('saves').createIndex({ user_id: 1 }),
  ]);
}
